_LANGUAGES = {"en": _EN_FULL, "hi": _HI}


class StockWiseLang:
    """Active language. Mirrors :class:`app.theme.StockWiseTheme`'s in-place switch."""

    mode: str = "en"

    @classmethod
    def apply(cls, mode: str | None = None) -> None:
        if mode in _LANGUAGES:
            cls.mode = mode

    @classmethod
    def toggle(cls) -> str:
        cls.apply("hi" if cls.mode == "en" else "en")
        return cls.mode

    @classmethod
    def is_hindi(cls) -> bool:
        return cls.mode == "hi"

    @classmethod
    def options(cls) -> list[tuple[str, str]]:
        """(code, native label) pairs for the language dropdown."""
        return [("en", "English"), ("hi", "हिन्दी")]


def t(key: str, **kwargs: Any) -> str:
    """Translate ``key`` into the active language.

    Falls back to English and then to the key itself, so a missing translation
    shows a readable label rather than ``nav.sales``. Positional placeholders use
    ``{name}`` and are substituted from ``kwargs``.
    """
    table = _LANGUAGES.get(StockWiseLang.mode, _EN_FULL)
    text = table.get(key) or _EN_FULL.get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


# Activate the default language so the class attribute is set from import time.
StockWiseLang.apply("en")

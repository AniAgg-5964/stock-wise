"""StockWise — language layer (English / हिन्दी).

Mirrors :mod:`app.theme` exactly. The theme activates a palette in place and
every view reads ``T.*`` at build time, so flipping the tokens and re-rendering
picks the change up everywhere. A language needs the same trick and no more:
``t()`` looks the key up in whichever dictionary is active when the view is
built, so a language switch is one state change plus a re-render.

**What is translated: app chrome only.** Product names, supplier names, shop
name, notes and CSV contents are the shop's own data and are never translated.
Technical model jargon — ``XGBoost``, ``WAPE``, ``Baseline``, ``Holdout`` — stays
in Latin script, because those terms are *already* how the numbers are discussed
and translating them would make them less readable, not more.

**Numbers are not translated.** Digits stay Western (``123``), the rupee sign and
Indian lakh grouping are untouched, and money stays ``Decimal`` end to end. Only
words change.

**Hindi is deliberately phrased as short noun phrases**, not full sentences. That
is how Indian retail signage reads, it keeps each label inside the layout
budgets measured in ``kpi_card`` (a metric label has ~144px), and it avoids the
gender/number agreement errors that creep into machine-drafted full sentences.
Measured with the real font: Mukta's Devanagari is *narrower* than Latin, so the
English layout survives the switch.

A missing key falls back to its English text and then to the key itself, so a
half-finished translation degrades to English instead of showing ``nav.sales`` to
a shopkeeper.
"""


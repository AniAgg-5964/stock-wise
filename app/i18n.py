def method_label(domain_label: str, *, default: str | None = None) -> str:
    """Translate a stored method label, passing unknown values through.

    Model metrics are persisted by label, so this is the one place that has to
    bridge stored English to the active language without inventing a translation
    for a label it does not recognise.
    """
    key = _METHOD_BY_DOMAIN_LABEL.get((domain_label or "").strip())
    if key is not None:
        return t(key)
    return default if default is not None else (domain_label or "")


def t(key: str, **kwargs: Any) -> str:
    """Translate ``key`` into the active language.

    Falls back to English and then to the key itself, so a missing translation
    shows a readable label rather than ``nav.sales``. Positional placeholders use
    ``{name}`` and are substituted from ``kwargs``.

    ``default=`` passes a value through untouched, which is what lets a stored
    domain string (a baseline method name, a movement reason) be translated when
    it happens to match a key and left alone when it does not.
    """
    if kwargs.get("default") is not None and key not in _LANGUAGES.get(StockWiseLang.mode, {}) \
            and key not in _EN_FULL:
        return str(kwargs.pop("default"))
    table = _LANGUAGES.get(StockWiseLang.mode, _EN_FULL)
    text = table.get(key) or _EN_FULL.get(key) or key
    kwargs.pop("default", None)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text



"""StockWise — repository interfaces (contracts).

Repositories own all SQL and transaction participation. Services orchestrate
them; the UI never touches repositories or SQL directly.
"""

from __future__ import annotations

from typing import Optional, Protocol, Sequence

from domain.entities import (
    ExternalSource,
    InventoryBatch,
    Product,
    ProductSupplier,
    Sale,
    SaleItem,
    StockMovement,
    Supplier,
    SupplierObservation,
)
from domain.enums import MovementType


class IProductRepository(Protocol):
    def create(self, product: Product, conn=None) -> Product: ...
    def update(self, product: Product, conn=None) -> Product: ...
    def get_by_id(self, product_id: int, conn=None) -> Optional[Product]: ...
    def get_by_sku(self, sku: str, conn=None) -> Optional[Product]: ...
    def list_all(self, active_only: bool = True, category: str | None = None,
                 search_query: str | None = None, conn=None) -> Sequence[Product]: ...
    def archive(self, product_id: int, conn=None) -> bool: ...
    def count(self, active_only: bool = True, conn=None) -> int: ...


class ISupplierRepository(Protocol):
    def create(self, supplier: Supplier, conn=None) -> Supplier: ...
    def update(self, supplier: Supplier, conn=None) -> Supplier: ...
    def get_by_id(self, supplier_id: int, conn=None) -> Optional[Supplier]: ...
    def list_all(self, active_only: bool = True, conn=None) -> Sequence[Supplier]: ...
    def archive(self, supplier_id: int, conn=None) -> bool: ...
    def link_product_supplier(self, link: ProductSupplier, conn=None) -> ProductSupplier: ...
    def get_product_suppliers(self, product_id: int, conn=None) -> Sequence[tuple[ProductSupplier, Supplier]]: ...
    def get_preferred_supplier(self, product_id: int, conn=None) -> Optional[tuple[ProductSupplier, Supplier]]: ...


class IInventoryRepository(Protocol):
    def add_movement(self, movement: StockMovement, conn=None) -> StockMovement: ...
    def get_stock_movements(self, product_id: int | None = None, limit: int = 100, conn=None) -> Sequence[StockMovement]: ...
    def create_batch(self, batch: InventoryBatch, conn=None) -> InventoryBatch: ...
    def get_batches_for_product(self, product_id: int, include_depleted: bool = False, conn=None) -> Sequence[InventoryBatch]: ...
    def update_batch_remaining(self, batch_id: int, remaining: float, conn=None) -> None: ...
    def stock_level(self, product_id: int, conn=None) -> float: ...
    def usable_stock(self, product_id: int, as_of: str | None = None, conn=None) -> float: ...


class ISalesRepository(Protocol):
    def create_sale(self, sale: Sale, conn=None) -> Sale: ...
    def get_sale(self, sale_id: int, conn=None) -> Optional[Sale]: ...
    def get_items(self, sale_id: int, conn=None) -> Sequence[SaleItem]: ...
    def find_by_external_ref(self, source: str, external_ref: str, conn=None) -> Optional[Sale]: ...
    def list_recent(self, limit: int = 50, conn=None) -> Sequence[Sale]: ...


class IExternalSourceRepository(Protocol):
    """Web pages consulted during supplier research."""

    def create(self, source: ExternalSource, conn=None) -> ExternalSource: ...
    def get_by_id(self, source_id: int, conn=None) -> Optional[ExternalSource]: ...
    def find_recent_by_url(self, url: str, within_minutes: int, conn=None) -> Optional[ExternalSource]: ...
    def set_parse_status(self, source_id: int, parse_status: str,
                         content_hash: str | None = None, conn=None) -> None: ...
    def list_by_query(self, query: str, limit: int = 20, conn=None) -> Sequence[ExternalSource]: ...
    def count(self, conn=None) -> int: ...


class ISupplierObservationRepository(Protocol):
    """Candidate facts extracted from research pages (unverified until applied)."""

    def create_many(self, observations: Sequence[SupplierObservation], conn=None) -> list[SupplierObservation]: ...
    def get_by_id(self, observation_id: int, conn=None) -> Optional[SupplierObservation]: ...
    def list_for_product(self, product_id: int, only_unverified: bool = False,
                         conn=None) -> Sequence[SupplierObservation]: ...
    def list_for_source(self, source_id: int, conn=None) -> Sequence[SupplierObservation]: ...
    def list_recent(self, limit: int = 50, conn=None) -> Sequence[SupplierObservation]: ...
    def mark_verified(self, observation_id: int, verified: bool = True, conn=None) -> None: ...
    def delete(self, observation_id: int, conn=None) -> bool: ...
    def count(self, conn=None) -> int: ...
